"""Generates specs/001-mars-photo-downloader/traceability.md from spec.md, tasks.md and the test sources.

Requirement (spec FR/SC) -> tasks that cite it -> test files those tasks name; AC-n -> tests tagged [Trait("AC","AC-n")].
Run from the repo root:  python scripts/gen_traceability.py
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
feature = root / "specs" / "001-mars-photo-downloader"
spec = (feature / "spec.md").read_text(encoding="utf8")
tasks = (feature / "tasks.md").read_text(encoding="utf8")

reqs = {}
for m in re.finditer(r"^- \*\*((?:FR|SC)-\d{3})[^*]*\*\*:?\s*(.+)$", spec, re.M):
    reqs[m.group(1)] = re.sub(r"\s*\[.*$", "", m.group(2)).strip()[:110]

task_rows = []
for line in tasks.splitlines():
    m = re.match(r"- \[(.)\] (T\d{3}) (.*)", line)
    if m:
        done, tid, body = m.groups()
        files = sorted(set(re.findall(r"`((?:tests|src)/[\w./-]+\.(?:cs|ts))`", body)))
        task_rows.append((tid, done.upper() == "X", body, files))


def cites(body: str, key: str) -> bool:
    if re.search(rf"(?<![\w.]){key}\b", body):
        return True
    if key.startswith("FR"):
        n = int(key[3:])
        for a, b in re.findall(r"FR-(0\d\d)[–-]FR-(0\d\d)", body):
            if int(a) <= n <= int(b):
                return True
    return False


lines = [
    "# Traceability Matrix",
    "",
    "Generated by `scripts/gen_traceability.py` from `spec.md`, `tasks.md` and the test sources. Do not edit by hand.",
    "",
    "## Requirement to tasks to tests",
    "",
    "| Requirement | Summary | Tasks | Test files |",
    "|---|---|---|---|",
]
orphans = []
for key, summary in reqs.items():
    hits = [t for t in task_rows if cites(t[2], key)]
    if not hits:
        orphans.append(key)
    tasks_cell = ", ".join(f"{t[0]}{'' if t[1] else ' (open)'}" for t in hits) or "NONE"
    tests = sorted({Path(f).name for t in hits for f in t[3] if f.startswith("tests/") or f.endswith(".spec.ts")})
    lines.append(f"| {key} | {summary} | {tasks_cell} | {', '.join(tests) or '-'} |")

lines += ["", "## Acceptance criteria to tests", "", "| Criterion | Tests tagged with it |", "|---|---|"]
ac = {}
for path in list((root / "tests").rglob("*.cs")):
    text = path.read_text(encoding="utf8", errors="replace")
    for m in re.finditer(r'\[Trait\("AC", "(AC-\d+)"\)\]', text):
        ac.setdefault(m.group(1), set()).add(path.name)
for n in range(1, 13):
    key = f"AC-{n}"
    lines.append(f"| {key} | {', '.join(sorted(ac.get(key, []))) or 'manual / see verification.md'} |")

lines += ["", "## Gaps", ""]
if orphans:
    lines.append("Requirements with no task: " + ", ".join(orphans))
else:
    lines.append("- Every functional requirement and success criterion is cited by at least one task.")
open_tasks = [t[0] for t in task_rows if not t[1]]
lines.append(f"- Open tasks at generation time: {', '.join(open_tasks) if open_tasks else 'none'}.")
unreferenced = [t[0] for t in task_rows if not re.search(r"FR-|SC-|AC-|SEC-|NFR|Constitution|D-\d|DEL|R-\d|Plan|REQ|US\d|contracts", t[2])]
lines.append(f"- Tasks with no requirement reference: {', '.join(unreferenced) if unreferenced else 'none'}.")

(feature / "traceability.md").write_text("\n".join(lines) + "\n", encoding="utf8")
print(f"{len(reqs)} requirements, {len(task_rows)} tasks, orphans: {orphans or 'none'}")
